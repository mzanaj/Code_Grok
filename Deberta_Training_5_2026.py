def main():
    parser = argparse.ArgumentParser(description="DeBERTa Binary Classification")
    parser.add_argument("--mode", choices=["search", "train", "full", "inference"],
                        default="full", help="Pipeline stage to run")
    parser.add_argument("--data_path", type=str, required=True)
    parser.add_argument("--output_dir", type=str, default="./results")
    parser.add_argument("--text_column", type=str, default="text")
    parser.add_argument("--label_column", type=str, default="label")
    parser.add_argument("--base_id_column", type=str, default="base_id")
    parser.add_argument("--n_trials", type=int, default=15)
    parser.add_argument("--cv_folds", type=int, default=3)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--model_dir", type=str, default=None,
                        help="Path to saved model (for inference mode)")
    args = parser.parse_args()

    config = Config(
        data_path=args.data_path,
        output_dir=args.output_dir,
        text_column=args.text_column,
        label_column=args.label_column,
        base_id_column=args.base_id_column,
        n_trials=args.n_trials,
        cv_folds=args.cv_folds,
        seed=args.seed,
    )

    print("\n" + "=" * 70)
    print("  DeBERTa Binary Classification Pipeline")
    print("=" * 70)
    print(f"  Mode    : {args.mode}")
    print(f"  Model   : {config.model_name}")
    print(f"  Device  : {config.device}")
    print(f"  Data    : {config.data_path}")

    # -----------------------------------------------------------
    if args.mode == "search":
        df = load_and_clean(config)
        best_params = run_search(config, df)

    # -----------------------------------------------------------
    elif args.mode == "train":
        df = load_and_clean(config)
        # Load best params if they exist from a prior search
        bp_path = Path(config.output_dir) / "best_hyperparameters.json"
        best_params = None
        if bp_path.exists():
            best_params = json.loads(bp_path.read_text()).get("params")
            print(f"  Loaded best params from {bp_path}")
        run_final_training(config, df, best_params)

    # -----------------------------------------------------------
    elif args.mode == "full":
        df = load_and_clean(config)
        best_params = run_search(config, df)
        run_final_training(config, df, best_params)

    # -----------------------------------------------------------
    elif args.mode == "inference":
        model_dir = args.model_dir or str(Path(config.output_dir) / "final_model")
        clf = Classifier(model_dir)

        df = pd.read_csv(args.data_path)
        assert config.text_column in df.columns

        print(f"\n  Running inference on {len(df):,} rows ...")
        preds = clf.predict(df[config.text_column].tolist())
        df["pred_label"] = [p["label"] for p in preds]
        df["flagged"] = [p["flagged"] for p in preds]
        df["pred_confidence"] = [p["confidence"] for p in preds]
        df["prob_positive"] = [p["prob_positive"] for p in preds]
        df["prob_negative"] = [p["probs"][0] for p in preds]

        n_flagged = df["flagged"].sum()
        print(f"  Flagged: {n_flagged:,} / {len(df):,}  ({n_flagged/len(df)*100:.1f}%)")
        print(f"  Threshold used: {clf.threshold:.3f}")

        out_path = Path(config.output_dir) / "predictions.csv"
        df.to_csv(out_path, index=False)
        print(f"  Predictions saved to {out_path}")

    print("\n  Done.\n")


if __name__ == "__main__":
    main()
