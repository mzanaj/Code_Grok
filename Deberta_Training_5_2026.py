# SECTION 5b: WEIGHTED TRAINER  (handles class imbalance)
# =============================================================================

class WeightedTrainer(Trainer):
    """
    Custom Trainer that applies inverse-frequency class weights to the
    cross-entropy loss.  The minority class (positive) gets a higher
    weight so the model pays more attention to it.
    """

    def __init__(self, class_weights: torch.Tensor = None, **kwargs):
        super().__init__(**kwargs)
        self.class_weights = class_weights

    def compute_loss(self, model, inputs, return_outputs=False, **kwargs):
        labels = inputs.pop("labels")
        outputs = model(**inputs)
        logits = outputs.logits

        if self.class_weights is not None:
            weight = self.class_weights.to(logits.device)
            loss_fn = torch.nn.CrossEntropyLoss(weight=weight)
        else:
            loss_fn = torch.nn.CrossEntropyLoss()

        loss = loss_fn(logits, labels)
        return (loss, outputs) if return_outputs else loss


def compute_class_weights(labels: List[int]) -> torch.Tensor:
    """
    Compute inverse-frequency weights so that the minority class
    contributes equally to the loss.

    With 60% negative / 40% positive:
      negative weight ≈ 0.83,  positive weight ≈ 1.25
    The model is penalised more for missing a positive.
    """
    counts = np.bincount(labels)
    total = len(labels)
    weights = total / (len(counts) * counts)
    weights = weights / weights.sum() * len(counts)  # normalise
    print(f"  Class weights: {dict(enumerate(np.round(weights, 3)))}")
    return torch.tensor(weights, dtype=torch.float32)


