def compute_metrics(eval_pred) -> Dict[str, float]:
    """
    Chunk-level metrics used during training.
    (Document-level aggregation happens in the final evaluation step.)
    """
    logits, labels = eval_pred
    probs = torch.softmax(torch.tensor(logits), dim=-1).numpy()
    preds = np.argmax(logits, axis=-1)

    return {
        "accuracy": float(accuracy_score(labels, preds)),
        "f1": float(f1_score(labels, preds, average="binary", pos_label=1)),
        "precision": float(precision_score(labels, preds, average="binary", pos_label=1)),
        "recall": float(recall_score(labels, preds, average="binary", pos_label=1)),
        "auc_roc": float(roc_auc_score(labels, probs[:, 1])),
    }


def document_level_evaluate(
    trainer: Trainer,
    dataset: HFDataset,
    doc_ids: List[int],
    true_labels: List[int],
    split_name: str = "Test",
    threshold: float = 0.5,
) -> Dict[str, float]:
    """
    Aggregate chunk predictions back to document level via mean-pooling,
    then compute metrics on the full documents — not individual chunks.

    This is the honest evaluation: one prediction per original text row.
    """
    print(f"\n{'=' * 70}")
    print(f"  DOCUMENT-LEVEL EVALUATION  —  {split_name.upper()}  (threshold={threshold:.2f})")
    print(f"{'=' * 70}")

    output = trainer.predict(dataset)
    logits = output.predictions
    probs = torch.softmax(torch.tensor(logits), dim=-1).numpy()

    # Group chunks by doc_id, mean-pool probabilities
    doc_probs = defaultdict(list)
    for doc_id, prob in zip(doc_ids, probs):
        doc_probs[doc_id].append(prob)

    # Build document-level predictions in original order
    unique_docs = sorted(doc_probs.keys())
    doc_pred_probs = []
    doc_true = []
    for doc_id in unique_docs:
        mean_prob = np.mean(doc_probs[doc_id], axis=0)
        doc_pred_probs.append(mean_prob)
        # true label: same for all chunks of a doc, take first
        idx = doc_ids.index(doc_id)
        doc_true.append(true_labels[idx])

    doc_pred_probs = np.array(doc_pred_probs)
    # Apply threshold: flag as positive if P(positive) >= threshold
    doc_preds = (doc_pred_probs[:, 1] >= threshold).astype(int)
    doc_true = np.array(doc_true)

    acc = accuracy_score(doc_true, doc_preds)
    f1 = f1_score(doc_true, doc_preds, average="binary", pos_label=1)
    prec = precision_score(doc_true, doc_preds, average="binary", pos_label=1)
    rec = recall_score(doc_true, doc_preds, average="binary", pos_label=1)
    auc = roc_auc_score(doc_true, doc_pred_probs[:, 1])

    results = {
        "accuracy": acc, "f1": f1, "precision": prec,
        "recall": rec, "auc_roc": auc, "threshold": threshold,
    }

    print(f"\n  Documents evaluated : {len(unique_docs)}")
    for name, val in results.items():
        print(f"  {name:20s}: {val:.4f}")

    print(f"\n  Classification Report:")
    print(classification_report(
        doc_true, doc_preds,
        target_names=["negative", "positive"], digits=4,
    ))

    cm = confusion_matrix(doc_true, doc_preds)
    print(f"  Confusion Matrix:")
    print(f"  {cm}\n")

    return results


