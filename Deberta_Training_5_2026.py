class Classifier:
    """
    Load a saved model and classify new texts.
    Handles long texts via chunking + probability aggregation automatically.
    """

    def __init__(self, model_dir: str, device: str = None, threshold: float = None):
        self.device = device or ("cuda" if torch.cuda.is_available() else "cpu")
        self.tokenizer = AutoTokenizer.from_pretrained(model_dir)
        self.model = AutoModelForSequenceClassification.from_pretrained(model_dir)
        self.model.to(self.device)
        self.model.eval()

        # Load config if available
        cfg_path = Path(model_dir) / "config.json"
        if cfg_path.exists():
            self.config = Config.load(str(cfg_path))
        else:
            self.config = Config()

        # Load tuned threshold (saved during training)
        if threshold is not None:
            self.threshold = threshold
        else:
            thresh_path = Path(model_dir) / "threshold.json"
            if thresh_path.exists():
                self.threshold = json.loads(thresh_path.read_text())["flag_threshold"]
            else:
                self.threshold = self.config.flag_threshold

        print(f"  Model loaded from {model_dir}  (device={self.device})")
        print(f"  Flag threshold: {self.threshold:.3f}")

    def predict(
        self, texts: List[str], batch_size: int = 64
    ) -> List[Dict[str, Any]]:
        """
        Classify a list of texts using the tuned threshold.

        Returns a list of dicts:
          [{"label": 1, "flagged": True, "confidence": 0.94,
            "prob_positive": 0.94, "probs": [0.06, 0.94]}, ...]

        Long texts are automatically chunked and aggregated.
        """
        # Chunk all texts, tracking which chunks belong to which doc
        all_input_ids, all_attn, all_doc_ids = [], [], []
        for doc_idx, text in enumerate(texts):
            chunks = tokenize_with_chunks(
                texts=[text],
                labels=[0],  # dummy
                tokenizer=self.tokenizer,
                max_length=self.config.max_length,
                overlap=self.config.chunk_overlap,
                doc_ids=[doc_idx],
            )
            all_input_ids.extend(chunks["input_ids"])
            all_attn.extend(chunks["attention_mask"])
            all_doc_ids.extend(chunks["doc_id"])

        # Run inference in batches
        all_probs = []
        for i in range(0, len(all_input_ids), batch_size):
            batch_ids = torch.tensor(all_input_ids[i : i + batch_size]).to(self.device)
            batch_attn = torch.tensor(all_attn[i : i + batch_size]).to(self.device)
            with torch.no_grad():
                logits = self.model(input_ids=batch_ids, attention_mask=batch_attn).logits
            probs = torch.softmax(logits, dim=-1).cpu().numpy()
            all_probs.extend(probs)

        # Aggregate by doc_id
        doc_probs = defaultdict(list)
        for doc_id, prob in zip(all_doc_ids, all_probs):
            doc_probs[doc_id].append(prob)

        results = []
        for doc_idx in range(len(texts)):
            mean_prob = np.mean(doc_probs[doc_idx], axis=0)
            prob_positive = float(mean_prob[1])
            flagged = prob_positive >= self.threshold
            label = 1 if flagged else 0
            results.append({
                "label": label,
                "flagged": flagged,
                "confidence": float(mean_prob[label]),
                "prob_positive": prob_positive,
                "probs": mean_prob.tolist(),
            })

        return results

    def predict_single(self, text: str) -> Dict[str, Any]:
        return self.predict([text])[0]


