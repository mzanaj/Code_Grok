# SECTION 5c: THRESHOLD TUNING  (optimise for flagging)
# =============================================================================

def tune_threshold(
    trainer: Trainer,
    dataset: HFDataset,
    doc_ids: List[int],
    true_labels: List[int],
    optimize_for: str = "f1",
    min_recall: Optional[float] = None,
) -> float:
    """
    Sweep thresholds on the validation set to find the optimal one.

    Args:
        optimize_for: "f1" (balanced) or "recall" (catch everything)
        min_recall: if set, only consider thresholds that achieve at
                    least this recall (e.g. 0.90 = miss at most 10%)

    Returns the best threshold.
    """
    print(f"\n{'=' * 70}")
    print("  THRESHOLD TUNING")
    print(f"{'=' * 70}")

    output = trainer.predict(dataset)
    probs = torch.softmax(torch.tensor(output.predictions), dim=-1).numpy()

    # Aggregate to document level
    doc_probs_map = defaultdict(list)
    for doc_id, prob in zip(doc_ids, probs):
        doc_probs_map[doc_id].append(prob)

    unique_docs = sorted(doc_probs_map.keys())
    doc_pos_probs = []
    doc_true = []
    for doc_id in unique_docs:
        doc_pos_probs.append(np.mean(doc_probs_map[doc_id], axis=0)[1])
        idx = doc_ids.index(doc_id)
        doc_true.append(true_labels[idx])

    doc_pos_probs = np.array(doc_pos_probs)
    doc_true = np.array(doc_true)

    # Sweep
    best_thresh, best_score = 0.5, 0.0
    print(f"\n  {'Thresh':>8s}  {'Prec':>6s}  {'Recall':>6s}  {'F1':>6s}  {'Note'}")
    print(f"  {'─' * 45}")

    for thresh in np.arange(0.20, 0.80, 0.025):
        preds = (doc_pos_probs >= thresh).astype(int)
        if preds.sum() == 0:
            continue
        p = precision_score(doc_true, preds, pos_label=1, zero_division=0)
        r = recall_score(doc_true, preds, pos_label=1, zero_division=0)
        f = f1_score(doc_true, preds, pos_label=1, zero_division=0)

        if min_recall and r < min_recall:
            note = "  (below min_recall)"
        else:
            note = ""
            score = f if optimize_for == "f1" else r
            if score > best_score:
                best_score = score
                best_thresh = thresh
                note = "  ← best"

        print(f"  {thresh:>8.3f}  {p:>6.3f}  {r:>6.3f}  {f:>6.3f}{note}")

    print(f"\n  Selected threshold: {best_thresh:.3f}  "
          f"(optimized for {optimize_for}, score={best_score:.4f})")

    return float(best_thresh)


