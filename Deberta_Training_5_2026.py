def load_and_clean(config: Config) -> pd.DataFrame:
    """Load data from disk, validate columns, clean text, report stats."""
    print("\n" + "=" * 70)
    print("  LOADING & CLEANING DATA")
    print("=" * 70)

    p = Path(config.data_path)
    if p.suffix == ".csv":
        df = pd.read_csv(p)
    elif p.suffix == ".json":
        df = pd.read_json(p)
    elif p.suffix == ".jsonl":
        df = pd.read_json(p, lines=True)
    elif p.suffix == ".parquet":
        df = pd.read_parquet(p)
    else:
        raise ValueError(f"Unsupported format: {p.suffix}")

    print(f"  Loaded {len(df):,} rows  |  columns: {df.columns.tolist()}")

    # Validate required columns
    for col in [config.text_column, config.label_column, config.base_id_column]:
        assert col in df.columns, f"Missing column: '{col}'"

    # Encode labels if string
    if df[config.label_column].dtype == "object":
        unique = sorted(df[config.label_column].unique())
        label_map = {lab: i for i, lab in enumerate(unique)}
        df[config.label_column] = df[config.label_column].map(label_map)
        print(f"  Mapped labels: {label_map}")
        map_path = Path(config.output_dir) / "label_map.json"
        with open(map_path, "w") as f:
            json.dump(label_map, f, indent=2)

    # Clean
    original_len = len(df)
    df["_clean"] = df[config.text_column].apply(
        lambda t: TextCleaner.clean(
            t,
            min_length=config.min_text_length,
            replace_urls=config.replace_urls,
            replace_emails=config.replace_emails,
        )
    )
    df = df[df["_clean"].str.len() > 0].reset_index(drop=True)
    if config.remove_duplicates:
        df = df.drop_duplicates(subset=["_clean"]).reset_index(drop=True)
    df[config.text_column] = df["_clean"]
    df.drop(columns=["_clean"], inplace=True)

    removed = original_len - len(df)
    print(f"  After cleaning: {len(df):,} rows  (removed {removed:,})")

    # Quick stats
    n_base = df[config.base_id_column].nunique()
    label_dist = df[config.label_column].value_counts().to_dict()
    lengths = df[config.text_column].str.split().str.len()
    pct_long = (lengths > config.max_length).mean() * 100

    print(f"  Base IDs       : {n_base}")
    print(f"  Label dist     : {label_dist}")
    print(f"  Text lengths   : median={lengths.median():.0f}, "
          f"max={lengths.max()}, >512 tokens={pct_long:.1f}%")

    return df


