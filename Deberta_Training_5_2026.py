# SECTION 4: CHUNKED TOKENISATION
# =============================================================================

def tokenize_with_chunks(
    texts: List[str],
    labels: List[int],
    tokenizer,
    max_length: int = 512,
    overlap: int = 128,
    doc_ids: Optional[List[int]] = None,
) -> dict:
    """
    Tokenise a list of texts.  Texts longer than max_length are split into
    overlapping windows so that NO content is discarded.

    Returns a dict with:
      input_ids, attention_mask, labels        – for Trainer
      doc_id                                   – maps each chunk back to its
                                                 parent row (needed for
                                                 aggregation at eval time)
    """
    all_input_ids = []
    all_attention_mask = []
    all_labels = []
    all_doc_ids = []

    stride = max_length - overlap  # how far each window advances

    for idx, (text, label) in enumerate(zip(texts, labels)):
        encoded = tokenizer(
            text,
            add_special_tokens=False,  # we'll add them per chunk
            return_attention_mask=False,
        )
        token_ids = encoded["input_ids"]

        # If short enough, single chunk (most common path)
        if len(token_ids) <= max_length - 2:  # room for [CLS] + [SEP]
            chunk_enc = tokenizer(
                text,
                max_length=max_length,
                padding="max_length",
                truncation=True,
            )
            all_input_ids.append(chunk_enc["input_ids"])
            all_attention_mask.append(chunk_enc["attention_mask"])
            all_labels.append(label)
            all_doc_ids.append(doc_ids[idx] if doc_ids else idx)
        else:
            # Sliding window over raw token ids
            for start in range(0, len(token_ids), stride):
                end = start + max_length - 2  # reserve for special tokens
                chunk_tokens = token_ids[start:end]

                # Build chunk with special tokens
                chunk_ids = (
                    [tokenizer.cls_token_id]
                    + chunk_tokens
                    + [tokenizer.sep_token_id]
                )
                attn = [1] * len(chunk_ids)

                # Pad
                pad_len = max_length - len(chunk_ids)
                chunk_ids += [tokenizer.pad_token_id] * pad_len
                attn += [0] * pad_len

                all_input_ids.append(chunk_ids)
                all_attention_mask.append(attn)
                all_labels.append(label)
                all_doc_ids.append(doc_ids[idx] if doc_ids else idx)

                # Stop if we've covered the end
                if end >= len(token_ids):
                    break

    return {
        "input_ids": all_input_ids,
        "attention_mask": all_attention_mask,
        "labels": all_labels,
        "doc_id": all_doc_ids,
    }


def build_hf_dataset(chunk_dict: dict) -> HFDataset:
    """Convert the chunked dict into a HuggingFace Dataset for Trainer."""
    ds = HFDataset.from_dict({
        "input_ids": chunk_dict["input_ids"],
        "attention_mask": chunk_dict["attention_mask"],
        "labels": chunk_dict["labels"],
        "doc_id": chunk_dict["doc_id"],
    })
    ds.set_format(type="torch", columns=["input_ids", "attention_mask", "labels"])
    return ds


