# SECTION 6: CORE TRAINING FUNCTION
# =============================================================================

def run_training(
    config: Config,
    train_df: pd.DataFrame,
    val_df: pd.DataFrame,
    test_df: Optional[pd.DataFrame] = None,
    trial_tag: str = "",
) -> Tuple[Trainer, Dict]:
    """
    Train a single model given train/val dataframes.
    Optionally evaluate on test_df.  Returns (trainer, metrics).
    """
    set_seed(config.seed)

    # -- tokenizer --
    tokenizer = AutoTokenizer.from_pretrained(config.model_name)

    # -- tokenize with chunking --
    print(f"\n  Tokenizing train ({len(train_df)} rows) ...")
    train_chunks = tokenize_with_chunks(
        texts=train_df[config.text_column].tolist(),
        labels=train_df[config.label_column].tolist(),
        tokenizer=tokenizer,
        max_length=config.max_length,
        overlap=config.chunk_overlap,
    )
    train_ds = build_hf_dataset(train_chunks)
    print(f"    → {len(train_ds)} chunks (from {len(train_df)} documents)")

    print(f"  Tokenizing val ({len(val_df)} rows) ...")
    val_chunks = tokenize_with_chunks(
        texts=val_df[config.text_column].tolist(),
        labels=val_df[config.label_column].tolist(),
        tokenizer=tokenizer,
        max_length=config.max_length,
        overlap=config.chunk_overlap,
    )
    val_ds = build_hf_dataset(val_chunks)
    print(f"    → {len(val_ds)} chunks (from {len(val_df)} documents)")

    # -- model --
    model = AutoModelForSequenceClassification.from_pretrained(
        config.model_name,
        num_labels=config.num_labels,
        hidden_dropout_prob=config.dropout,
        attention_probs_dropout_prob=config.dropout,
    )

    tag = trial_tag or datetime.now().strftime("%Y%m%d_%H%M%S")
    run_output = os.path.join(config.output_dir, tag)

    training_args = TrainingArguments(
        output_dir=run_output,
        num_train_epochs=config.num_epochs,
        per_device_train_batch_size=config.batch_size,
        per_device_eval_batch_size=config.batch_size * 2,
        learning_rate=config.learning_rate,
        weight_decay=config.weight_decay,
        warmup_ratio=config.warmup_ratio,
        fp16=config.fp16,
        bf16=config.bf16,
        gradient_accumulation_steps=config.gradient_accumulation_steps,
        max_grad_norm=config.max_grad_norm,
        gradient_checkpointing=config.gradient_checkpointing,
        eval_strategy=config.eval_strategy,
        eval_steps=config.eval_steps if config.eval_strategy == "steps" else None,
        save_strategy=config.save_strategy,
        save_steps=config.save_steps if config.save_strategy == "steps" else None,
        save_total_limit=config.save_total_limit,
        load_best_model_at_end=config.load_best_model_at_end,
        metric_for_best_model=config.metric_for_best_model,
        greater_is_better=config.greater_is_better,
        logging_steps=config.logging_steps,
        report_to=config.report_to if config.report_to != "none" else [],
        seed=config.seed,
        dataloader_num_workers=config.dataloader_num_workers,
        remove_unused_columns=True,
    )

    # -- class weights for imbalanced data --
    class_weights = None
    if config.use_class_weights:
        class_weights = compute_class_weights(train_chunks["labels"])

    trainer = WeightedTrainer(
        class_weights=class_weights,
        model=model,
        args=training_args,
        train_dataset=train_ds,
        eval_dataset=val_ds,
        tokenizer=tokenizer,
        compute_metrics=compute_metrics,
        callbacks=[
            EarlyStoppingCallback(early_stopping_patience=config.early_stopping_patience)
        ],
    )

    # -- train --
    trainer.train()

    # -- val metrics (chunk-level, used for model selection) --
    val_metrics = trainer.evaluate(val_ds)

    # -- threshold tuning on validation set --
    threshold = config.flag_threshold
    threshold = tune_threshold(
        trainer=trainer,
        dataset=val_ds,
        doc_ids=val_chunks["doc_id"],
        true_labels=val_chunks["labels"],
        optimize_for="f1",       # change to "recall" if you want to catch more
        min_recall=None,         # set e.g. 0.90 to enforce minimum recall
    )

    # -- test evaluation (document-level, honest numbers, tuned threshold) --
    test_results = {}
    if test_df is not None:
        test_chunks = tokenize_with_chunks(
            texts=test_df[config.text_column].tolist(),
            labels=test_df[config.label_column].tolist(),
            tokenizer=tokenizer,
            max_length=config.max_length,
            overlap=config.chunk_overlap,
        )
        test_ds = build_hf_dataset(test_chunks)

        test_results = document_level_evaluate(
            trainer=trainer,
            dataset=test_ds,
            doc_ids=test_chunks["doc_id"],
            true_labels=test_chunks["labels"],
            split_name="Test",
            threshold=threshold,
        )

    return trainer, {
        **val_metrics,
        "tuned_threshold": threshold,
        **{f"test_{k}": v for k, v in test_results.items()},
    }


