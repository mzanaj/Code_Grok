# =============================================================================

def run_final_training(config: Config, df: pd.DataFrame, best_params: Optional[dict] = None):
    """
    Train on the full train split with the best hyperparameters,
    evaluate on test, save the final model for production use.
    """
    print("\n" + "=" * 70)
    print("  FINAL MODEL TRAINING")
    print("=" * 70)

    # Apply best params if provided
    if best_params:
        for k, v in best_params.items():
            if hasattr(config, k):
                setattr(config, k, v)
        print("  Applied best hyperparameters from search.")

    # Group-stratified 3-way split
    train_df, val_df, test_df = group_stratified_split(
        df,
        label_col=config.label_column,
        group_col=config.base_id_column,
        train_ratio=config.train_ratio,
        val_ratio=config.val_ratio,
        seed=config.seed,
    )

    _print_split_summary(train_df, val_df, test_df, config)

    trainer, results = run_training(
        config, train_df, val_df, test_df, trial_tag="final_model"
    )

    # -- save everything --
    model_dir = Path(config.output_dir) / "final_model"
    trainer.save_model(str(model_dir))
    trainer.tokenizer.save_pretrained(str(model_dir))

    # Save threshold so the Classifier can load it automatically
    tuned_threshold = results.get("tuned_threshold", 0.5)
    config.flag_threshold = tuned_threshold
    config.save(str(model_dir / "config.json"))

    threshold_path = model_dir / "threshold.json"
    with open(threshold_path, "w") as f:
        json.dump({"flag_threshold": tuned_threshold}, f, indent=2)

    results_path = Path(config.output_dir) / "final_results.json"
    with open(results_path, "w") as f:
        # filter to JSON-serializable values
        serializable = {k: v for k, v in results.items() if isinstance(v, (int, float, str))}
        json.dump(serializable, f, indent=2)

    print(f"\n  Model saved to  : {model_dir}")
    print(f"  Results saved to: {results_path}")

    return trainer, results


def _print_split_summary(train_df, val_df, test_df, config):
    total = len(train_df) + len(val_df) + len(test_df)
    for name, split in [("Train", train_df), ("Val", val_df), ("Test", test_df)]:
        n = len(split)
        n_groups = split[config.base_id_column].nunique()
        label_dist = split[config.label_column].value_counts().to_dict()
        print(f"  {name:5s}: {n:>6,} rows  |  {n_groups:>3} base IDs  |  "
              f"labels: {label_dist}  ({n/total*100:.1f}%)")


