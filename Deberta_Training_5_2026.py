class TextCleaner:
    """
    Stateless text preprocessing.  Call TextCleaner.clean(text).
    Order: unicode → html → urls/emails → whitespace → length filter.
    """

    @staticmethod
    def clean(
        text: str,
        min_length: int = 3,
        replace_urls: bool = True,
        replace_emails: bool = True,
    ) -> str:
        if not isinstance(text, str) or pd.isna(text):
            return ""

        # 1. unicode normalisation
        text = unicodedata.normalize("NFKC", text)

        # 2. strip html
        text = re.sub(r"<[^>]+>", "", text)
        text = re.sub(r"&\w+;", "", text)

        # 3. urls & emails
        if replace_urls:
            text = re.sub(r"http\S+|www\.\S+", "[URL]", text)
        if replace_emails:
            text = re.sub(r"\S+@\S+", "[EMAIL]", text)

        # 4. whitespace
        text = re.sub(r"\s+", " ", text).strip()

        # 5. length gate
        if len(text.split()) < min_length:
            return ""

        return text


