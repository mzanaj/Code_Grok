def run_search(config: Config, df: pd.DataFrame) -> dict:
    """
    Bayesian hyperparameter search with Optuna.

    Each trial trains on a group-stratified train/val split (no base_id
    leakage) and returns the validation F1.  The best params are saved
    to disk and returned.
    """
    if not OPTUNA_AVAILABLE:
        raise ImportError("Install optuna:  pip install optuna")

    print("\n" + "=" * 70)
    print("  HYPERPARAMETER SEARCH")
    print("=" * 70)
    print(f"  Trials        : {config.n_trials}")
    print(f"  CV folds      : {config.cv_folds}")
    print(f"  Search space  : lr, batch_size, epochs, warmup, weight_decay, dropout")

    # Pre-split: hold out a true test set that is NEVER seen during search
    train_val_df, test_df = _split_train_test(df, config)

    def objective(trial: optuna.Trial) -> float:
        # -- sample hyperparameters --
        lr = trial.suggest_float("learning_rate", 1e-5, 5e-5, log=True)
        bs = trial.suggest_categorical("batch_size", [16, 32])
        epochs = trial.suggest_int("num_epochs", 3, 5)
        warmup = trial.suggest_float("warmup_ratio", 0.05, 0.20)
        wd = trial.suggest_float("weight_decay", 0.005, 0.05)
        dropout = trial.suggest_float("dropout", 0.05, 0.20)

        trial_config = Config(
            **{
                **asdict(config),
                "learning_rate": lr,
                "batch_size": bs,
                "num_epochs": epochs,
                "warmup_ratio": warmup,
                "weight_decay": wd,
                "dropout": dropout,
                "report_to": "none",
                "eval_strategy": "epoch",
                "save_strategy": "epoch",
            }
        )

        # -- grouped CV on the train_val portion --
        groups = train_val_df[config.base_id_column].values
        labels = train_val_df[config.label_column].values
        sgkf = StratifiedGroupKFold(
            n_splits=config.cv_folds, shuffle=True, random_state=config.seed
        )

        fold_scores = []
        for fold_i, (train_idx, val_idx) in enumerate(sgkf.split(train_val_df, labels, groups)):
            print(f"\n  Trial {trial.number} / Fold {fold_i + 1}")
            fold_train = train_val_df.iloc[train_idx].reset_index(drop=True)
            fold_val = train_val_df.iloc[val_idx].reset_index(drop=True)

            try:
                _, metrics = run_training(
                    trial_config,
                    fold_train,
                    fold_val,
                    test_df=None,
                    trial_tag=f"search/trial_{trial.number}_fold_{fold_i}",
                )
                f1_val = metrics.get("eval_f1", 0.0)
                fold_scores.append(f1_val)
            except Exception as e:
                print(f"  ⚠  Fold failed: {e}")
                fold_scores.append(0.0)

        mean_f1 = float(np.mean(fold_scores))
        print(f"\n  Trial {trial.number}  →  mean F1 = {mean_f1:.4f}  (folds: {fold_scores})")
        return mean_f1

    study = optuna.create_study(direction="maximize", study_name="deberta_search")
    study.optimize(objective, n_trials=config.n_trials, show_progress_bar=True)

    # -- report --
    print("\n" + "=" * 70)
    print("  SEARCH COMPLETE")
    print("=" * 70)
    print(f"  Best trial   : {study.best_trial.number}")
    print(f"  Best F1 (CV) : {study.best_value:.4f}")
    print(f"  Best params  :")
    for k, v in study.best_params.items():
        print(f"    {k:20s}: {v}")

    # -- save --
    best_path = Path(config.output_dir) / "best_hyperparameters.json"
    with open(best_path, "w") as f:
        json.dump(
            {"best_f1_cv": study.best_value, "params": study.best_params},
            f, indent=2,
        )
    print(f"\n  Saved to {best_path}")

    return study.best_params


def _split_train_test(df, config):
    """
    Quick group-stratified split into train_val (85%) and test (15%)
    for use during search.  The test set is untouched until final eval.
    """
    group_df = (
        df.groupby(config.base_id_column)[config.label_column]
        .agg(lambda x: x.mode().iloc[0])
        .reset_index()
        .rename(columns={config.label_column: "_strat"})
    )
    tv_groups, te_groups = train_test_split(
        group_df, test_size=config.test_ratio,
        stratify=group_df["_strat"], random_state=config.seed,
    )
    tv_ids = set(tv_groups[config.base_id_column])
    te_ids = set(te_groups[config.base_id_column])
    return (
        df[df[config.base_id_column].isin(tv_ids)].reset_index(drop=True),
        df[df[config.base_id_column].isin(te_ids)].reset_index(drop=True),
    )


