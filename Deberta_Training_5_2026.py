# SECTION 3: GROUP-STRATIFIED DATA SPLITTING
# =============================================================================

def group_stratified_split(
    df: pd.DataFrame,
    label_col: str,
    group_col: str,
    train_ratio: float,
    val_ratio: float,
    seed: int,
) -> Tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame]:
    """
    Split so that NO base_id appears in more than one partition.

    Strategy:
      1. Collapse to one row per base_id (majority label for stratification).
      2. Stratified-split the base_ids into train / val / test.
      3. Expand back to full rows.

    This prevents data leakage between synthetic siblings.
    """
    # one row per group: take majority label for stratification key
    group_df = (
        df.groupby(group_col)[label_col]
        .agg(lambda x: x.mode().iloc[0])
        .reset_index()
        .rename(columns={label_col: "_strat_label"})
    )

    # first cut: train vs (val+test)
    holdout_ratio = 1.0 - train_ratio
    train_groups, temp_groups = train_test_split(
        group_df,
        test_size=holdout_ratio,
        random_state=seed,
        stratify=group_df["_strat_label"],
    )

    # second cut: val vs test
    val_share = val_ratio / (val_ratio + (1.0 - train_ratio - val_ratio))
    val_groups, test_groups = train_test_split(
        temp_groups,
        test_size=(1.0 - val_share),
        random_state=seed,
        stratify=temp_groups["_strat_label"],
    )

    train_ids = set(train_groups[group_col])
    val_ids = set(val_groups[group_col])
    test_ids = set(test_groups[group_col])

    # sanity: no overlap
    assert train_ids.isdisjoint(val_ids) and train_ids.isdisjoint(test_ids)

    train_df = df[df[group_col].isin(train_ids)].reset_index(drop=True)
    val_df = df[df[group_col].isin(val_ids)].reset_index(drop=True)
    test_df = df[df[group_col].isin(test_ids)].reset_index(drop=True)

    return train_df, val_df, test_df


